    # ---- fixtures -------------------------------------------------------
    def write_registry(self, script: str | None = None, with_merge_binding: bool = True) -> None:
        script_item = script or (
            "- uid: Script\n  type: script\n  file: Script.js\n  name: Global Script\n"
        )
        remote_option = ("    merge: remote-merge\n    rules: SubscriptionRules\n"
                         if with_merge_binding else "    rules: SubscriptionRules\n")
        registry = (
            "current: remote-a\nitems:\n"
            + script_item
            + "- uid: SubscriptionRules\n  type: rules\n  file: SubscriptionRules.yaml\n"
            + "- uid: remote-merge\n  type: merge\n  file: subscription-merge.yaml\n"
            + "- uid: Merge\n  type: merge\n  file: Merge.yaml\n"
            + "- uid: remote-a\n  type: remote\n  name: Fixed Profile\n  file: subscription.yaml\n"
            + "  option:\n" + remote_option
        )
        (self.state / "profiles.yaml").write_text(registry, encoding="utf-8")

    def write_rules(self, direct: str | None = None, proxy: str | None = None) -> None:
        (self.rules / "direct.yaml").write_text(direct or (
            'version: 1\npre:\n  - "DOMAIN,force.example,DIRECT"\n'
            'post:\n  - "DOMAIN-SUFFIX,cn,DIRECT"\n'
        ), encoding="utf-8")
        (self.rules / "proxy.yaml").write_text(proxy or (
            'version: 1\npre: []\npost: []\n'
        ), encoding="utf-8")

    def declare_wechat_proxy(self, installed: bool = True) -> None:
        self.write_rules(proxy=(
            'version: 1\npre:\n  - app: wechat\n    target: Proxy\npost: []\n'
        ))
        packages = {"wechat": [str(self.app_executable)]} if installed else {}
        self.manifest.write_text(json.dumps(packages), encoding="utf-8")

    # ---- drivers --------------------------------------------------------
    def environment(self, **overrides: object) -> dict[str, str]:
        environment = dict(os.environ)
        environment.update({
            "HOME": str(self.home),
            "RULES_DIR": str(self.rules),
            "PATH": f"{self.bin}:{os.environ['PATH']}",
            "DPKG_LOG": str(self.dpkg_log),
            "DPKG_MAP": str(self.manifest),
            "SSH_LOG": str(self.ssh_log),
            "PROBE_LOG": str(self.probe_log),
        })
        environment.update({key: str(value) for key, value in overrides.items()})
        return environment

    def run_menu(self, *inputs: str, expected: int = 0, cwd: Path | None = None,
                 environment: dict[str, str] | None = None, script: Path | None = None) -> subprocess.CompletedProcess:
        result = subprocess.run(
            ["bash", str(script or ENTRY)], cwd=str(cwd or self.root),
            env=environment or self.environment(), input="".join(inputs),
            text=True, capture_output=True, check=False, timeout=120,
        )
        self.assertEqual(
            result.returncode, expected,
            f"menu rc={result.returncode}, expected {expected}\nstdout:\n{result.stdout}\nstderr:\n{result.stderr}",
        )
        if self.probe_log.exists():
            self.fail("a guarded network command ran: " + self.probe_log.read_text())
        return result

    def run_entry(self, *arguments: str, expected: int = 0, input: str | None = None,
                  cwd: Path | None = None, environment: dict[str, str] | None = None) -> subprocess.CompletedProcess:
        result = subprocess.run(
            ["bash", str(ENTRY), *arguments], cwd=str(cwd or self.root),
            env=environment or self.environment(), input=input,
            text=True, capture_output=True, check=False, timeout=120,
        )
        self.assertEqual(
            result.returncode, expected,
            f"entry rc={result.returncode}, expected {expected}\nstdout:\n{result.stdout}\nstderr:\n{result.stderr}",
        )
        return result

    # ---- helpers --------------------------------------------------------
    def snapshot(self, include_mtime: bool = False) -> dict[str, object]:
        """Byte snapshot of every fixture file outside the temporary tool dirs."""
        watched = [self.state, self.home / ".ssh", self.rules]
        snapshot: dict[str, object] = {}
        for base in watched:
            for path in sorted(base.rglob("*")):
                if path.is_symlink():
                    snapshot[str(path)] = ("symlink", os.readlink(path))
                    continue
                if not path.is_file():
                    snapshot[str(path)] = ("directory", stat.S_IMODE(path.stat().st_mode))
                    continue
                entry: dict[str, object] = {"sha256": digest(path), "mode": stat.S_IMODE(path.stat().st_mode)}
                if include_mtime:
                    entry["mtime_ns"] = path.stat().st_mtime_ns
                snapshot[str(path)] = entry
        return snapshot

    def backups(self) -> list[Path]:
        return sorted(path for path in self.profiles.glob(f"{self.script.name}.backup.*") if path.is_file())

    def changed_paths(self, before: dict[str, object], after: dict[str, object]) -> set[str]:
        return {path for path in set(before) | set(after) if before.get(path) != after.get(path)}

