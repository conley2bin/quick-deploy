    # ---- update ownership ----------------------------------------------
    def test_update_touches_only_registered_script_and_its_backups(self) -> None:
        self.declare_wechat_proxy()
        before = self.snapshot(include_mtime=True)
        self.run_menu("1\n", "0\n")
        after = self.snapshot(include_mtime=True)
        changed = self.changed_paths(before, after)
        allowed = {str(self.script)} | {str(path) for path in self.backups()}
        self.assertTrue(changed <= allowed, f"update touched unexpected paths: {sorted(changed - allowed)}")
        self.assertIn(str(self.script), changed)
        self.assertEqual(len(self.backups()), 1)
        require(BACKUP_RE.search(self.backups()[0].name), self.backups()[0].name)
        self.assertEqual((self.profiles / "Merge.yaml").read_text(), "# merge sentinel\nmode: rule\n")
        self.assertEqual((self.profiles / "subscription-merge.yaml").read_text(), "# subscription merge sentinel\n")
        self.assertEqual((self.state / "clash-verge.yaml").read_text(), "# runtime sentinel\n")
        self.assertEqual(self.ssh_config.read_text(), "# existing host\nHost existing.example\n    Port 22\n")
        self.assertFalse(self.ssh_log.exists(), "routing update invoked ssh")
        for sentinel in ("Merge.yaml", "subscription-merge.yaml", "SubscriptionRules.yaml", "subscription.yaml"):
            self.assertEqual(digest(self.profiles / sentinel),
                             before[str(self.profiles / sentinel)]["sha256"], sentinel)

